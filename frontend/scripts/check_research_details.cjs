// Offline rendering regression for failed/provisional research, without a browser or new dependencies.
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const filename = path.resolve(__dirname, '../src/app/dashboard/components/ResearchDetails.tsx');
const output = ts.transpileModule(fs.readFileSync(filename,'utf8'), {compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2021}}).outputText;
const compiled = new Module(filename,module);
compiled.filename=filename;
compiled.paths=module.paths;
compiled._compile(output,filename);
const Component=compiled.exports.default;
const result={status:'unavailable',profile:{mode:'deep',song:{title:'7 Minute Drill',artist:'J. Cole',version:'original'},profile:{lyrical_emotions:[{label:'sad',level:'unknown',explanation:'Evidence unavailable.',finding_ids:[]}]},findings:[],sources:[{id:'1',kind:'written_excerpt',url:'https://example.com/review',title:'Song review',text:'Actual retrieved source excerpt',research_role:'reviews'}],errors:[{code:'TimeoutError'}],cached:false},comparison:{similarities:[],differences:[]}};
const render=()=>renderToStaticMarkup(React.createElement(Component,{result}));
let html=render();
assert.ok(html.includes('Actual retrieved source excerpt'));
assert.ok(html.includes('No reliable AI profile'));
assert.ok(html.includes('Local AI reached its time budget'));
assert.ok(!html.includes('Evidence unavailable.'));
assert.ok(!html.includes('No supported shared ratings yet'));
assert.ok(!html.includes('<h4>Lyrical emotions'));
result.status='running'; result.profile.analysis_status='running';
html=render();
assert.ok(html.includes('Actual retrieved source excerpt'));
assert.ok(html.includes('AI interpretation is still running'));
result.profile.profile.lyrical_emotions.push({label:'longing',level:'high',explanation:'Supported by an accepted lyric finding.',finding_ids:[0]});
html=render();
assert.ok(html.includes('longing'));
assert.ok(!html.includes('Evidence unavailable.'));
console.log('Research detail rendering checks passed: retained sources, honest timeout, no unknown grid, progressive and supported ratings.');
